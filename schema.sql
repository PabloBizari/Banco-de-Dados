-- WK Materiais de Construção · banco MySQL 8 (versão corrigida do arquivo exportado)
SET NAMES utf8mb4;
CREATE DATABASE IF NOT EXISTS wk_materiais CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE wk_materiais;

CREATE TABLE CLIENTE (
  ID_CLIENTE INT AUTO_INCREMENT PRIMARY KEY,
  NM_CLIENTE VARCHAR(120) NOT NULL,
  NR_CPF_CNPJ VARCHAR(20) NULL,
  NR_TELEFONE VARCHAR(20) NULL,
  DS_ENDERECO VARCHAR(255) NULL,
  IN_ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
  VL_LIMITE_FIADO DECIMAL(10,2) NULL,
  DT_CONSENTIMENTO DATE NULL,
  DT_ANONIMIZACAO DATETIME NULL
);

CREATE TABLE PRODUTO (
  ID_PRODUTO INT AUTO_INCREMENT PRIMARY KEY,
  NM_PRODUTO VARCHAR(100) NOT NULL,
  DS_CATEGORIA VARCHAR(50) NULL,
  VL_PRECO_VENDA DECIMAL(10,2) NOT NULL,
  QT_ESTOQUE DECIMAL(10,2) NOT NULL DEFAULT 0,
  IN_ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
  VL_CUSTO DECIMAL(10,2) NULL,
  PC_MARGEM DECIMAL(5,2) NULL,
  CHECK (QT_ESTOQUE >= 0)
);

CREATE TABLE FORNECEDOR (
  ID_FORNECEDOR INT AUTO_INCREMENT PRIMARY KEY,
  NM_RAZAO_SOCIAL VARCHAR(100) NOT NULL,
  NR_CNPJ VARCHAR(20) NOT NULL,
  NR_TELEFONE VARCHAR(20) NOT NULL,
  IN_ATIVO BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE CAIXA (
  ID_CAIXA INT AUTO_INCREMENT PRIMARY KEY,
  DT_CAIXA DATE NOT NULL UNIQUE,
  VL_ABERTURA DECIMAL(10,2) NOT NULL DEFAULT 0,
  VL_FECHAMENTO DECIMAL(10,2) NULL,
  DT_FECHAMENTO DATETIME NULL
);

CREATE TABLE VENDA (
  ID_VENDA INT AUTO_INCREMENT PRIMARY KEY,
  DT_VENDA DATETIME NOT NULL,
  TP_PAGAMENTO VARCHAR(20) NOT NULL,
  VL_TOTAL DECIMAL(10,2) NOT NULL,
  VL_DESCONTO DECIMAL(10,2) NOT NULL DEFAULT 0,
  ID_CLIENTE INT NULL,
  NR_PARCELAS TINYINT NOT NULL DEFAULT 1,
  NR_CUPOM_FISCAL VARCHAR(44) NULL,
  ID_CAIXA INT NOT NULL,
  FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE),
  FOREIGN KEY (ID_CAIXA) REFERENCES CAIXA (ID_CAIXA),
  CHECK (TP_PAGAMENTO IN ('DINHEIRO','PIX','DEBITO','CREDITO','FIADO')),
  CHECK (TP_PAGAMENTO <> 'FIADO' OR ID_CLIENTE IS NOT NULL)
);

CREATE TABLE ITEM_VENDA (
  ID_VENDA INT NOT NULL,
  ID_PRODUTO INT NOT NULL,
  QT_VENDIDA DECIMAL(10,2) NOT NULL,
  VL_UNITARIO_APLICADO DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (ID_VENDA, ID_PRODUTO),
  FOREIGN KEY (ID_VENDA) REFERENCES VENDA (ID_VENDA),
  FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO (ID_PRODUTO)
);

CREATE TABLE CONTAS_A_RECEBER (
  ID_CONTA INT AUTO_INCREMENT PRIMARY KEY,
  ID_VENDA INT NOT NULL UNIQUE,
  ID_CLIENTE INT NOT NULL,
  VL_DEBITO DECIMAL(10,2) NOT NULL,
  DT_LANCAMENTO DATE NOT NULL,
  DT_VENCIMENTO DATE NOT NULL,
  DT_PAGAMENTO DATE NULL,
  TP_STATUS VARCHAR(20) NOT NULL DEFAULT 'ABERTO',
  FOREIGN KEY (ID_VENDA) REFERENCES VENDA (ID_VENDA),
  FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE)
);

CREATE TABLE DEVOLUCAO (
  ID_DEVOLUCAO INT AUTO_INCREMENT PRIMARY KEY,
  ID_VENDA INT NOT NULL,
  DT_DEVOLUCAO DATETIME NOT NULL,
  DS_MOTIVO VARCHAR(255) NOT NULL,
  TP_DESTINO ENUM('CREDITO','TROCA') NOT NULL,
  VL_CREDITO DECIMAL(10,2) NOT NULL DEFAULT 0,
  FOREIGN KEY (ID_VENDA) REFERENCES VENDA (ID_VENDA)
);

CREATE TABLE ITEM_DEVOLUCAO (
  ID_DEVOLUCAO INT NOT NULL,
  ID_PRODUTO INT NOT NULL,
  QT_DEVOLVIDA DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (ID_DEVOLUCAO, ID_PRODUTO),
  FOREIGN KEY (ID_DEVOLUCAO) REFERENCES DEVOLUCAO (ID_DEVOLUCAO),
  FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO (ID_PRODUTO)
);

CREATE TABLE PEDIDO_COMPRA (
  ID_PEDIDO_COMPRA INT AUTO_INCREMENT PRIMARY KEY,
  ID_FORNECEDOR INT NOT NULL,
  DT_PEDIDO DATE NOT NULL,
  VL_TOTAL_PEDIDO DECIMAL(10,2) NOT NULL,
  TP_STATUS VARCHAR(20) NOT NULL,
  DT_RECEBIMENTO DATE NULL,
  FOREIGN KEY (ID_FORNECEDOR) REFERENCES FORNECEDOR (ID_FORNECEDOR)
);

CREATE TABLE ITEM_PEDIDO_COMPRA (
  ID_PEDIDO_COMPRA INT NOT NULL,
  ID_PRODUTO INT NOT NULL,
  QT_PEDIDA DECIMAL(10,2) NOT NULL,
  QT_RECEBIDA DECIMAL(10,2) NULL,
  VL_CUSTO_UNITARIO DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (ID_PEDIDO_COMPRA, ID_PRODUTO),
  FOREIGN KEY (ID_PEDIDO_COMPRA) REFERENCES PEDIDO_COMPRA (ID_PEDIDO_COMPRA),
  FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO (ID_PRODUTO)
);

CREATE TABLE CONTAS_A_PAGAR (
  ID_CONTA_PAGAR INT AUTO_INCREMENT PRIMARY KEY,
  ID_PEDIDO_COMPRA INT NOT NULL UNIQUE,
  ID_FORNECEDOR INT NOT NULL,
  VL_DEBITO DECIMAL(10,2) NOT NULL,
  DT_LANCAMENTO DATE NOT NULL,
  DT_VENCIMENTO DATE NOT NULL,
  DT_PAGAMENTO DATE NULL,
  TP_STATUS VARCHAR(20) NOT NULL DEFAULT 'ABERTO',
  FOREIGN KEY (ID_PEDIDO_COMPRA) REFERENCES PEDIDO_COMPRA (ID_PEDIDO_COMPRA),
  FOREIGN KEY (ID_FORNECEDOR) REFERENCES FORNECEDOR (ID_FORNECEDOR)
);

